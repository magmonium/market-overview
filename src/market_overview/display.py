"""Value → display, and the day's headline figure — the Python side of the renderer's own rules. (0085_13)

⚠️ **These are mirrors, and they are mirrors because of the subprocess boundary.** The video's numbers are formatted by
`remotion/theme.ts` and its headline figure chosen by `remotion/headline.ts`; the metadata cannot import either, so
the only honest option is a second implementation that is *documented as one* and **pinned against the first by a
test**. `test_metadata.py` renders the golden bundle's expectation from both sides.

The alternative — letting each surface format independently — is the failure this module exists to prevent. Issue 13's
rule is one bundle, three surfaces: a description quoting `-0.70%` where the video shows `−0.70%` is a different
string, and a description naming a different index than the cold open is a different *claim*. Neither would raise
anything anywhere.

⚠️ Not just tidiness either: `copybudget.py` already carried private copies of both of these. Consolidating them here
means the budget, the metadata and the video are arguing from **one** Python rule rather than three.
"""
from __future__ import annotations

from typing import Any

#: ⚠️ U+2212 MINUS SIGN, not a hyphen. `theme.ts` uses it so a minus is not a hyphen sitting next to a digit, and the
#: metadata has to match: `-0.70%` and `−0.70%` are different strings, and only one of them is what the video shows.
MINUS = "\u2212"
DASH = "\u2014"


def percent(value: float | None, digits: int = 2) -> str:
    """`theme.ts`'s `percent`, to the character."""
    if value is None:
        return DASH
    return f"{'+' if value >= 0 else MINUS}{abs(value):.{digits}f}%"


def _group_indian(digits: str) -> str:
    """`1234567` → `12,34,567`. The last three, then pairs — **not** Western grouping.

    ⚠️ Written out rather than reached for, because Python has no Indian grouping: `f"{n:,}"` gives `1,234,567`, which
    on an Indian finance product is simply the wrong number to a reader who knows the convention.
    """
    if len(digits) <= 3:
        return digits
    head, tail = digits[:-3], digits[-3:]
    pairs = []
    while len(head) > 2:
        pairs.insert(0, head[-2:])
        head = head[:-2]
    if head:
        pairs.insert(0, head)
    return ",".join([*pairs, tail])


def number(value: float | None, digits: int = 2) -> str:
    """`theme.ts`'s `number` — Indian digit grouping, so `1,23,456` rather than `123,456`."""
    if value is None:
        return DASH
    whole, _, fraction = f"{abs(value):.{digits}f}".partition(".")
    grouped = _group_indian(whole)
    sign = MINUS if value < 0 else ""
    return f"{sign}{grouped}.{fraction}" if fraction else f"{sign}{grouped}"


def crore(value: float | None) -> str:
    """`theme.ts`'s `crore`: rupees, rounded, Indian-grouped."""
    return DASH if value is None else f"\u20b9{number(round(value), 0)}"


#: The label key the brief leads on. Mirrors `HEADLINE_KEY` in `remotion/headline.ts` (pinned by `test_metadata.py`).
HEADLINE_KEY = "nifty50"


def headline(bundle: dict[str, Any]) -> dict[str, Any] | None:
    """The day's headline index fact — **Nifty 50**, falling back to the largest absolute move.

    ⚠️ Mirrors `remotion/headline.ts`'s `headline`, including both its rule and its totality: the brief leads on the
    index a reader means by *"the market"*, and an empty scoreboard returns `None` rather than raising. The metadata
    is generated by a *different* command from the video and meets whatever bundle it is handed, so it cannot rely on
    `cold_open` having been scheduled.
    """
    rows = bundle.get("indexes") or []
    if not rows:
        return None
    for row in rows:
        if row.get("label_key") == HEADLINE_KEY:
            return row
    # The fallback, kept so a bundle with no Nifty 50 row still leads with something real rather than a blank title.
    return max(rows, key=lambda row: abs((row.get("window") or {}).get("change") or 0))


def headline_label(bundle: dict[str, Any], labels: dict[str, Any]) -> str:
    """The headline index's name in this language, or `''` — never a raw slug in a finished description."""
    row = headline(bundle)
    if row is None:
        return ""
    key = row.get("label_key", "")
    return (labels.get("indexes") or {}).get(key, key)


def headline_change(bundle: dict[str, Any]) -> float | None:
    row = headline(bundle)
    return None if row is None else (row.get("window") or {}).get("change")
